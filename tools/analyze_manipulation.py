"""analyze_manipulation.py — aggregate mission reports (checklist 18.2-18.5).

Reads every logs/mission_report*.json (written by intellibot_controller at
DONE/ERROR) and writes docs/evidence/manipulation_results.md:

    * end-to-end result counts (DELIVERED / FAILED) — ALL runs, no exclusion
    * grasp / place attempts, docking errors (range, lateral, heading)
    * failure reasons (failure analysis, 18.4)
    * agreement between the robot's sensor verification and the Supervisor
      ground-truth audit (a disagreement is reported, never hidden)

Run:  python tools/analyze_manipulation.py [--logs logs] [--out docs/evidence/manipulation_results.md]
"""

import argparse
import collections
import glob
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))


def summarize(reports):
    n = len(reports)
    res = collections.Counter(r.get("result", "UNKNOWN") for r in reports)
    reasons = collections.Counter(r.get("failure_reason") for r in reports
                                  if r.get("result") != "DELIVERED")
    audits = [r["ground_truth_audit"] for r in reports if "ground_truth_audit" in r]
    agree = sum(1 for r in reports if "ground_truth_audit" in r
                and r["ground_truth_audit"]["in_slot"] == r.get("delivery_verified_by_sensors"))
    docks = [d for r in reports for d in r.get("docking", []) if d.get("status") == "DONE"]

    def stat(vals):
        vals = [abs(v) for v in vals if v is not None]
        if not vals:
            return "n/a"
        return f"{statistics.mean(vals):.3f} ± {statistics.pstdev(vals):.3f} (max {max(vals):.3f})"
    return {
        "n": n, "results": dict(res), "reasons": dict(reasons),
        "grasp_attempts": stat([r.get("grasp_attempts") for r in reports]),
        "place_attempts": stat([r.get("place_attempts") for r in reports]),
        "audit_n": len(audits), "audit_agree": agree,
        "audit_xy_err": stat([a["err_xy_m"] for a in audits]),
        "dock_lateral_m": stat([d.get("lateral_err_m") for d in docks]),
        "dock_heading_deg": stat([d.get("heading_err_deg") for d in docks]),
        "times": stat([r.get("time_s") for r in reports]),
    }


def write_md(s, out, files):
    lines = ["# Manipulation results (generated by tools/analyze_manipulation.py)", "",
             f"Runs analysed: **{s['n']}** (all mission_report*.json files; no exclusions)", "",
             "| metric | value |", "|---|---|"]
    lines += [f"| result counts | {s['results']} |",
              f"| mission time (s) | {s['times']} |",
              f"| grasp attempts per run | {s['grasp_attempts']} |",
              f"| place attempts per run | {s['place_attempts']} |",
              f"| docking lateral error (m) | {s['dock_lateral_m']} |",
              f"| docking heading error (deg) | {s['dock_heading_deg']} |",
              f"| ground-truth audit available | {s['audit_n']} runs |",
              f"| sensor verdict == ground truth | {s['audit_agree']} / {s['audit_n']} |",
              f"| placement error vs slot centre (m) | {s['audit_xy_err']} |", "",
              "## Failure analysis (18.4)", ""]
    if s["reasons"]:
        lines += ["| failure reason | count |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in sorted(s["reasons"].items(), key=lambda kv: -kv[1])]
    else:
        lines.append("No failed runs in this set.")
    lines += ["", "Source files: " + ", ".join(os.path.basename(f) for f in files)]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--logs", default=os.path.join(ROOT, "logs"))
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "evidence", "manipulation_results.md"))
    a = ap.parse_args(argv)
    files = sorted(glob.glob(os.path.join(a.logs, "mission_report*.json")))
    if not files:
        print(f"no mission_report*.json in {a.logs} — run the mission in Webots first")
        return 1
    reports = []
    for f in files:
        with open(f) as fh:
            reports.append(json.load(fh))
    s = summarize(reports)
    write_md(s, a.out, files)
    print(json.dumps(s, indent=2))
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
